class ProximityAgent():
    def __init__(self, model) -> None:
        self.model = model

    def group_by_similarity(self, hypotheses):
        '''
        Args:
            hypotheses (List[str]): 待分组的假设列表。

        Returns:
            List[List[str]]: 分组后的假设列表，每组包含2个假设。
        '''
        retry_count = 0
        embeddings = None
        while retry_count < 10:
            try:
                embeddings = self.model.embed_documents(hypotheses)
                if embeddings is not None:
                    break
            except TypeError as e:
                if "'NoneType' object is not iterable" in str(e):
                    retry_count += 1
                    continue
                else:
                    raise
            except Exception as e:
                retry_count += 1
                continue
        if embeddings is None:
            raise RuntimeError("Failed to get embeddings after 5 retries.")
        embeddings = np.array(embeddings)
        similarity_matrix = cosine_similarity(embeddings)
        np.fill_diagonal(similarity_matrix, -np.inf)
        ungrouped_indices = set(range(len(hypotheses)))
        groups = []
        while len(ungrouped_indices) >= 2:
            idx_a, idx_b = np.unravel_index(np.argmax(similarity_matrix), similarity_matrix.shape)
            idx_a, idx_b = int(idx_a), int(idx_b)
            # 添加分组
            groups.append([{idx_a:hypotheses[idx_a]}, {idx_b: hypotheses[idx_b]}])
            # 移除已分组的索引
            ungrouped_indices.remove(idx_a)
            ungrouped_indices.remove(idx_b)
            # 更新相似度矩阵，避免再次使用已经分组的成员
            similarity_matrix[idx_a, :] = -np.inf
            similarity_matrix[:, idx_a] = -np.inf
            similarity_matrix[idx_b, :] = -np.inf
            similarity_matrix[:, idx_b] = -np.inf

        # 若剩余单个成员，单独成组
        if ungrouped_indices:
            remaining_idx = ungrouped_indices.pop()
            groups.append([{remaining_idx:hypotheses[remaining_idx]}])

        return [[key for j in i for key in j.keys()] for i in groups ]


def similar_abstracts(abstracts, embedding_model, knowledge_path, top_n):
    '''
    abstract: abstract to compare with pubmed
    path: path of pubmed embedding
    '''
    vector_store = Chroma(
        collection_name="HCC_pubmed_abstracts",
        embedding_function=embedding_model,
        persist_directory=knowledge_path,  # Where to save data locally, remove if not necessary
    )
    top_results = {}
    for _, abs in enumerate(abstracts):
        retry_count = 0
        result = None
        while retry_count < 3:
            try:
                result = vector_store.similarity_search_with_score(abs, top_n)
                if result is not None:
                    break
            except Exception as e:
                pass
            retry_count += 1
        if result is None:
            top_results[_] = []
            continue
        top_results[_] = [
            {'pid': i[0].id, 'similarity': 1 - i[1], 'abstract': i[0].page_content}
            for i in result if i is not None
        ]
    return top_results

class RankingAgent():
    def __init__(self, chatModel) -> None:
        self.chatModel = chatModel.with_structured_output(Evaluator)
        self.internal_pk_template = ChatPromptTemplate([
            ('system', '''You are an expert evaluator tasked with comparing two hypotheses.
Evaluate the two provided hypotheses (hypothesis 1 and hypothesis 2) and determine which one
is superior based on the the novelty, plausibility, testability and safety.
Provide a concise rationale for your selection, concluding with the phrase "better idea: <1 or 2>".
Evaluation criteria:
1. novelty
2. plausibility
3. testability
4. safety
Considerations:
{notes}
Each hypothesis includes an independent review.These reviews may contain numerical scores.
Disregard these scores in your comparative analysis, as they may not be directly comparable across reviews.'''),
            ('user', '''
Hypothesis 1:
{hypothesis1}
Hypothesis 2:
{hypothesis2}
Review of hypothesis 1:
{review1}
Review of hypothesis 2:
{review2}
Reasoning and conclusion (end with "better hypothesis: <1 or 2>"):
             ''')
        ])

    def PK(self, hypotheses, reviews, group_index, path):
        self.save_path = os.path.join(path, 'PK')
        os.makedirs(self.save_path, exist_ok=True)
        messages = self.internal_pk_template.invoke({
            'hypothesis1': hypotheses[0],
            'hypothesis2': hypotheses[1],
            'review1': reviews[0],
            'review2': reviews[1],
            'notes': None
        })
        save_path = f'{self.save_path}/{group_index[0]}vs{group_index[1]}.json'
        if not os.path.exists(save_path):
            response = self.chatModel.invoke(messages)

            with open(save_path, 'w', encoding='utf-8') as f:
                f.write(response.model_dump_json(indent=4))
            
        else:
            with open(save_path, 'r', encoding='utf-8') as f:
                response = Evaluator(**json.load(f))
                
        return group_index[response.Choice-1]

