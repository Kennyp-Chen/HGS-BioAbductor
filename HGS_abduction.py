    async def internal_trial_system(self):
        # Generate initial content and build candidates with their original index concurrently
        general_content = await self.generation_agent.generate(self.triple, self.n_ask, self.save_path)
        # general_content = await self.review_genagent.generate(self.triple, self.n_ask, self.save_path)
        candidates = []
        for i, content in enumerate(general_content):
            candidates.append({
                "seed_index": i,
                "Hypothesis": content.Hypothesis,
                "Abstract": content.Abstract,
                "CausalChain": content.CausalChain
            })

        current_candidates = candidates
        round_counter = 1

        # Define an async helper to process a group of candidates concurrently
        async def process_group(group, round_counter):
            round_path = os.path.join(self.save_path, f'round{round_counter}')
            # Extract abstracts for the group and query similar abstracts
            group_abstracts = [current_candidates[i]["Abstract"] for i in group]
            logging.info('start query similar abstracts')
            top_results = similar_abstracts(group_abstracts, self.embeddingModel, self.knowledge_path, 3)

            # For each candidate in the group, concurrently obtain reflection reviews and aggregate them
            async def process_candidate(j, idx):
                orig_idx = current_candidates[idx]["seed_index"]
                logging.info(f'start review for candidate {orig_idx}')
                observe_task = await self.reflection_agent.observe(
                    [item['abstract'] for item in top_results[j]],
                    current_candidates[idx]["Hypothesis"],
                    orig_idx,
                    round_path
                )
                review_task_omics = await self.reflection_agent.review(
                    current_candidates[idx]["Hypothesis"],
                    'omics',
                    orig_idx,
                    round_path
                )
                review_task_cellular = await self.reflection_agent.review(
                    current_candidates[idx]["Hypothesis"],
                    'cellular biology',
                    orig_idx,
                    round_path
                )
                review_task_clinical = await self.reflection_agent.review(
                    current_candidates[idx]["Hypothesis"],
                    'clinical research',
                    orig_idx,
                    round_path
                )
                # Run all reflection tasks in parallel
                reviews = [observe_task, review_task_omics, review_task_cellular, review_task_clinical]
                agg = self.truth_loom.wrapup(reviews, orig_idx, round_path)
                return orig_idx, reviews, agg

            candidate_tasks = [process_candidate(j, idx) for j, idx in enumerate(group)]
            candidate_results = await asyncio.gather(*candidate_tasks)

            # Build the aggregated review list for the group in the original candidate order
            agg_rev = {res[0]: res[2] for res in candidate_results}

            group_hyps = [current_candidates[i]["Hypothesis"] for i in group]
            group_rev_list = [agg_rev[current_candidates[i]["seed_index"]] for i in group]
            logging.info('start PK ...')
            if len(group) == 2:
                winner_idx = self.ranking_agent.PK(
                    group_hyps,
                    group_rev_list,
                    [current_candidates[i]['seed_index'] for i in group],
                    round_path
                )
            else:
                winner_idx = [current_candidates[i]['seed_index'] for i in group][0]

            winner_candidate = next(candidate for candidate in current_candidates if candidate["seed_index"] == winner_idx)

            winner_reviews = next(item[1] for item in candidate_results if item[0] == winner_idx)
            logging.info('start evolve ...')
            evolved_winner = self.evo_agent.evolve(
                winner_candidate["Hypothesis"],
                winner_candidate["CausalChain"],
                winner_reviews,
                winner_candidate["seed_index"],
                round_path
            )
            
            return {
                "seed_index": winner_candidate["seed_index"],
                "Hypothesis": evolved_winner.Hypothesis,
                "Abstract": evolved_winner.Abstract,
                "CausalChain": evolved_winner.CausalChain
            }

        # Continue tournament rounds until only one candidate remains, processing groups in parallel
        while len(current_candidates) > 1:
            logging.info(f'start round {round_counter}')
            logging.info('start group by similarity')
            grouped_indices = self.proximity_agent.group_by_similarity(
                [cand["Hypothesis"] for cand in current_candidates]
            )
            group_tasks = [process_group(group, round_counter) for group in grouped_indices]
            next_round_candidates = await asyncio.gather(*group_tasks)
            current_candidates = next_round_candidates
            round_counter += 1

        # Save the final champion(s) with their original indices
        final_winner_file = os.path.join(self.save_path, "champion.json")
        with open(final_winner_file, "w") as f:
            json.dump(current_candidates, f, indent=4, ensure_ascii=False)
        
        viewpoints = await self.decomposer_agent.decompose(current_candidates, self.save_path)

        logging.info('process end')
        return current_candidates


